"""pulley.lock and the installed modules directory.

A modules directory holds one entry per import name, which is what the Flywheel compiler
searches: a directory with the package's files (registry and git packages), or a
``<name>.link`` file holding the path of a path dependency. Each installed directory has a
``.pulley.json`` record; Pulley only removes entries it installed.
"""

from __future__ import annotations

import json
import os
import shutil
import tomllib
from pathlib import Path

from .config import LOCKFILE, PulleyError
from .resolver import Package

RECORD = ".pulley.json"
SKIP = {".git", ".flywheel-modules", "__pycache__"}


def _quote(text: str) -> str:
    return json.dumps(text)


def read_lock(directory: Path) -> dict[tuple, dict]:
    """The packages recorded in a lock file, by resolver key."""
    path = directory / LOCKFILE
    if not path.is_file():
        return {}
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise PulleyError(f"{path}: {exc}; delete it and run `pulley install` to rebuild it") from None
    entries: dict[tuple, dict] = {}
    for entry in data.get("package", []):
        source = entry.get("source")
        if source == "registry":
            author, name = entry["distribution"].split(".", 1)
            key = ("registry", entry["registry"], author, name)
        elif source == "path":
            key = ("path", str((directory / entry["path"]).resolve()))
        elif source == "git":
            key = ("git", entry["git"], entry.get("rev", ""))
        else:
            continue
        entries[key] = entry
    return entries


def write_lock(directory: Path, packages: dict[tuple, Package]) -> None:
    lines = ["# Generated by Pulley. Do not edit by hand; `pulley install` keeps it current.", "version = 1", ""]
    for key in sorted(packages, key=lambda k: (sorted(packages[k].aliases), k)):
        p = packages[key]
        lines.append("[[package]]")
        lines.append("aliases = [" + ", ".join(_quote(a) for a in sorted(p.aliases)) + "]")
        lines.append(f"source = {_quote(p.kind)}")
        if p.kind == "registry":
            lines += [f"registry = {_quote(p.registry)}", f"distribution = {_quote(p.author + '.' + p.name)}",
                      f"version = {_quote(p.version)}", f"sha256 = {_quote(p.sha256)}"]
        elif p.kind == "path":
            lines.append(f"path = {_quote(os.path.relpath(p.path, directory))}")
        else:
            lines += [f"git = {_quote(p.git)}", f"rev = {_quote(p.rev)}", f"commit = {_quote(p.commit)}"]
        if p.dev:
            lines.append("dev = true")
        if p.edges:
            lines.append("dependencies = [" + ", ".join(_quote(a) for a in sorted(p.edges)) + "]")
        lines.append("")
    (directory / LOCKFILE).write_text("\n".join(lines), encoding="utf-8")


def _record(package: Package) -> dict:
    record = {"source": package.kind}
    if package.kind == "registry":
        record.update(registry=package.registry, distribution=f"{package.author}.{package.name}",
                      version=package.version, sha256=package.sha256)
    elif package.kind == "git":
        record.update(git=package.git, commit=package.commit)
    return record


def installed(modules: Path) -> dict[str, dict]:
    """What Pulley has installed in a modules directory: import name -> record."""
    result: dict[str, dict] = {}
    if not modules.is_dir():
        return result
    for entry in sorted(modules.iterdir()):
        if entry.is_dir() and (entry / RECORD).is_file():
            try:
                result[entry.name] = json.loads((entry / RECORD).read_text(encoding="utf-8"))
            except ValueError:
                result[entry.name] = {}
        elif entry.is_file() and entry.suffix == ".link":
            result[entry.stem] = {"source": "path", "path": entry.read_text(encoding="utf-8").strip()}
    return result


def _remove(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def _copy_tree(source: Path, destination: Path) -> None:
    shutil.copytree(source, destination, ignore=lambda d, names: [n for n in names if n in SKIP])


def sync(modules: Path, packages: dict[tuple, Package], include_dev: bool = True, log=print) -> dict[str, int]:
    """Makes a modules directory hold exactly the resolved packages. Returns change counts."""
    modules.mkdir(parents=True, exist_ok=True)
    wanted: dict[str, Package] = {}
    for package in packages.values():
        if package.dev and not include_dev:
            continue
        for alias in package.aliases:
            wanted[alias] = package
    current = installed(modules)
    counts = {"added": 0, "updated": 0, "removed": 0, "unchanged": 0}
    for alias, package in sorted(wanted.items()):
        directory, link = modules / alias, modules / f"{alias}.link"
        previous = current.get(alias)
        if package.kind == "path":
            target = str(Path(package.path).resolve())
            if previous == {"source": "path", "path": target}:
                counts["unchanged"] += 1
                continue
            for stale in (directory, link):
                if stale.exists() and (stale == link or (stale / RECORD).exists() or not any(stale.iterdir())):
                    _remove(stale)
                elif stale.exists():
                    raise PulleyError(f"{stale} exists and was not installed by Pulley; remove it first")
            link.write_text(target + "\n", encoding="utf-8")
        else:
            record = _record(package)
            if previous == record and directory.is_dir():
                counts["unchanged"] += 1
                continue
            if directory.exists() and not (directory / RECORD).exists():
                raise PulleyError(f"{directory} exists and was not installed by Pulley; remove it first")
            staging = modules / f".{alias}.installing"
            _remove(staging)
            _copy_tree(Path(package.path), staging)
            (staging / RECORD).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
            if link.exists():
                _remove(link)
            if directory.exists():
                old = modules / f".{alias}.old"
                _remove(old)
                directory.rename(old)
                staging.rename(directory)
                _remove(old)
            else:
                staging.rename(directory)
        counts["updated" if previous else "added"] += 1
        log(("updated" if previous else "added") + f" {alias} ({package.label})")
    for alias in sorted(set(current) - set(wanted)):
        _remove(modules / alias)
        _remove(modules / f"{alias}.link")
        counts["removed"] += 1
        log(f"removed {alias}")
    return counts
